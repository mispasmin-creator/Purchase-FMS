    const qtys = {};
    const statuses = {};
    const remarksMap = {};
    rows.forEach((indent) => {
      qtys[indent.id] = indent.approvedQty_original || indent.quantity;
      statuses[indent.id] = indent.status_original || "Select";
      remarksMap[indent.id] = indent.remark_original || "";
    });
